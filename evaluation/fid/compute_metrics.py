#!/usr/bin/env python3
"""
Compute the 8-metric suite (FID, SSIM, PSNR, MUSIQ, CLIP-Text, CLIP-Image,
Region CLIP-T, Region CLIP-I) on the 4000 panels generated by
evaluation/fid/infer_univl_shard.py.

Each panel is 1536x512 = [cond | gen | gt]. Filenames are
"{idx:05d}_{type}_{basename}_{objn}.jpg" — we recover type+objn from the name
and bbox from the source records JSONL (train_real_4k.jsonl).

This is the same metric implementation as evaluation/eval_univl.py.compute_metrics, just
run on a larger N where the small-sample bias is much smaller.

Usage:
    python3 evaluation/fid/compute_metrics.py \\
        --panels_dir output_inference/eval4k_Cn50 \\
        --records   output_inference/train_real_4k.jsonl \\
        --gpu 0 \\
        --out output_inference/eval4k_Cn50/metrics.json
"""
import argparse, glob, json, os, re
import numpy as np
import torch
import torch.nn.functional as F
from PIL import Image
import torchvision.transforms as T
from collections import defaultdict


TARGET_SIZE = (512, 512)
PANEL_W = 1536
CLIP_MODEL_NAME = "openai/clip-vit-large-patch14"


def split_panel(img):
    return (img.crop((0,    0, 512,  512)),
            img.crop((512,  0, 1024, 512)),
            img.crop((1024, 0, 1536, 512)))


def load_records_by_idx(jsonl_path):
    """Records are stored in order. Index = position in file."""
    out = []
    with open(jsonl_path) as f:
        for line in f:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def parse_idx_from_filename(name):
    """'00042_square_xxx_objn.jpg' -> 42"""
    m = re.match(r"(\d+)_", name)
    return int(m.group(1)) if m else None


def collect_panels(panels_dir, records):
    """Returns parallel lists: (gen_imgs, gt_imgs, gen_crops, gt_crops, text_labels, types)."""
    gen_imgs, gt_imgs, gen_crops, gt_crops, text_labels, record_types = [], [], [], [], [], []
    files = sorted(glob.glob(os.path.join(panels_dir, "*.jpg")))
    print(f"Found {len(files)} panels in {panels_dir}")
    for f in files:
        idx = parse_idx_from_filename(os.path.basename(f))
        if idx is None or idx >= len(records):
            continue
        rec = records[idx]
        img = Image.open(f).convert("RGB")
        if img.size[0] != PANEL_W:
            continue
        _, gen, gt = split_panel(img)
        gen_imgs.append(gen)
        gt_imgs.append(gt)
        text_labels.append(rec["objn"])
        record_types.append(rec["type"])
        # Crop bbox region in TARGET_SIZE coords
        bbox = rec["bbox"]
        # bbox is in original-image px; we need TARGET coords. Records have
        # cond_path, but we can rederive from gt size by reading the original
        # image. To save I/O: pull resolution from rec if present, else open gt.
        orig_w, orig_h = None, None
        if "resolution" in rec:
            orig_h = rec["resolution"].get("height")
            orig_w = rec["resolution"].get("width")
        if orig_w is None or orig_h is None:
            # Fall back: open original gt to get its native size (slow path).
            try:
                orig_w, orig_h = Image.open(rec["gt_path"]).size
            except Exception:
                orig_w, orig_h = TARGET_SIZE
        sx = TARGET_SIZE[0] / orig_w
        sy = TARGET_SIZE[1] / orig_h
        x1 = max(0, int(bbox[0]*sx))
        y1 = max(0, int(bbox[1]*sy))
        x2 = min(TARGET_SIZE[0], int(bbox[2]*sx))
        y2 = min(TARGET_SIZE[1], int(bbox[3]*sy))
        if x2 > x1 + 4 and y2 > y1 + 4:
            gen_crops.append(gen.crop((x1, y1, x2, y2)))
            gt_crops.append(gt.crop((x1, y1, x2, y2)))
    return gen_imgs, gt_imgs, gen_crops, gt_crops, text_labels, record_types


@torch.no_grad()
def compute_metrics(gen, gt, gen_crops, gt_crops, text_labels, types, device):
    from torchmetrics.image.fid import FrechetInceptionDistance
    from torchmetrics.image import StructuralSimilarityIndexMeasure, PeakSignalNoiseRatio
    from transformers import CLIPModel, CLIPProcessor
    import pyiqa

    to_tensor = T.ToTensor()
    results = {}
    n = len(gen)
    print(f"\nComputing metrics on {n} pairs...")

    # SSIM
    print("  SSIM...")
    ssim_metric = StructuralSimilarityIndexMeasure(data_range=1.0).to(device)
    ssim_vals = []
    for g, gt_i in zip(gen, gt):
        gt_t = to_tensor(gt_i).unsqueeze(0).to(device)
        g_t = to_tensor(g.resize(gt_i.size)).unsqueeze(0).to(device)
        ssim_vals.append(ssim_metric(g_t, gt_t).item())
    results["SSIM"] = float(np.mean(ssim_vals))

    # PSNR
    print("  PSNR...")
    psnr_metric = PeakSignalNoiseRatio(data_range=1.0).to(device)
    psnr_vals = []
    for g, gt_i in zip(gen, gt):
        gt_t = to_tensor(gt_i).unsqueeze(0).to(device)
        g_t = to_tensor(g.resize(gt_i.size)).unsqueeze(0).to(device)
        psnr_vals.append(psnr_metric(g_t, gt_t).item())
    results["PSNR"] = float(np.mean(psnr_vals))

    # FID
    print("  FID...")
    fid = FrechetInceptionDistance(feature=2048, normalize=True).to(device)
    bb = []
    for gt_i in gt:
        bb.append(to_tensor(gt_i.resize(TARGET_SIZE)))
        if len(bb) == 16:
            fid.update(torch.stack(bb).to(device), real=True); bb = []
    if bb: fid.update(torch.stack(bb).to(device), real=True); bb = []
    for g in gen:
        bb.append(to_tensor(g.resize(TARGET_SIZE)))
        if len(bb) == 16:
            fid.update(torch.stack(bb).to(device), real=False); bb = []
    if bb: fid.update(torch.stack(bb).to(device), real=False); bb = []
    try:
        results["FID"] = float(fid.compute().item())
    except Exception as e:
        print(f"  FID failed: {e}")
        results["FID"] = float("nan")

    # MUSIQ
    print("  MUSIQ...")
    musiq = pyiqa.create_metric("musiq", device=device)
    musiq_vals = []
    for g in gen:
        g_t = to_tensor(g.resize((512, 512))).unsqueeze(0).to(device)
        musiq_vals.append(musiq(g_t).item())
    results["MUSIQ"] = float(np.mean(musiq_vals))

    # CLIP
    print("  Loading CLIP ...")
    clip_model = CLIPModel.from_pretrained(CLIP_MODEL_NAME, torch_dtype=torch.float32).to(device).eval()
    clip_processor = CLIPProcessor.from_pretrained(CLIP_MODEL_NAME)

    print("  CLIP-Text ...")
    clip_text_vals = []
    for g, text in zip(gen, text_labels):
        inputs = clip_processor(text=[text], images=g, return_tensors="pt", padding=True).to(device)
        outputs = clip_model(**inputs)
        clip_text_vals.append((outputs.logits_per_image / 100.0).item())
    results["CLIP-Text"] = float(np.mean(clip_text_vals))

    print("  CLIP-Image ...")
    clip_img_vals = []
    for g, gt_i in zip(gen, gt):
        gi  = clip_processor(images=g,   return_tensors="pt").to(device)
        gti = clip_processor(images=gt_i, return_tensors="pt").to(device)
        gf  = F.normalize(clip_model.get_image_features(**gi),  dim=-1)
        gtf = F.normalize(clip_model.get_image_features(**gti), dim=-1)
        clip_img_vals.append((gf * gtf).sum(dim=-1).item())
    results["CLIP-Image"] = float(np.mean(clip_img_vals))

    print("  Region CLIP-T ...")
    region_text_vals = []
    for gc, text in zip(gen_crops, text_labels[:len(gen_crops)]):
        gc_r = gc.resize((224, 224))
        inputs = clip_processor(text=[text], images=gc_r, return_tensors="pt", padding=True).to(device)
        outputs = clip_model(**inputs)
        region_text_vals.append((outputs.logits_per_image / 100.0).item())
    results["Region CLIP-T"] = float(np.mean(region_text_vals)) if region_text_vals else float("nan")

    print("  Region CLIP-I ...")
    region_img_vals = []
    for gc, gtc in zip(gen_crops, gt_crops):
        gc_r = gc.resize((224, 224))
        gtc_r = gtc.resize((224, 224))
        gi  = clip_processor(images=gc_r,  return_tensors="pt").to(device)
        gti = clip_processor(images=gtc_r, return_tensors="pt").to(device)
        gf  = F.normalize(clip_model.get_image_features(**gi),  dim=-1)
        gtf = F.normalize(clip_model.get_image_features(**gti), dim=-1)
        region_img_vals.append((gf * gtf).sum(dim=-1).item())
    results["Region CLIP-I"] = float(np.mean(region_img_vals)) if region_img_vals else float("nan")

    # Per-type breakdown
    per_type = defaultdict(lambda: defaultdict(list))
    for i, t in enumerate(types):
        per_type[t]["SSIM"].append(ssim_vals[i])
        per_type[t]["PSNR"].append(psnr_vals[i])
        per_type[t]["CLIP-Image"].append(clip_img_vals[i])
        if i < len(clip_text_vals):
            per_type[t]["CLIP-Text"].append(clip_text_vals[i])
    results["per_type"] = {
        t: {k: float(np.mean(v)) for k, v in d.items()}
        for t, d in per_type.items()
    }

    del clip_model
    torch.cuda.empty_cache()
    return results


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--panels_dir", required=True)
    ap.add_argument("--records",    required=True)
    ap.add_argument("--gpu", type=int, default=0)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    device = f"cuda:{args.gpu}"
    torch.cuda.set_device(device)

    print(f"Loading records from {args.records}")
    records = load_records_by_idx(args.records)
    print(f"records: {len(records)}")

    gen, gt, gc, gtc, text, types = collect_panels(args.panels_dir, records)
    print(f"valid pairs: {len(gen)}, with-bbox-crop: {len(gc)}")

    results = compute_metrics(gen, gt, gc, gtc, text, types, device)

    # Print
    arrows = {"FID": "↓", "SSIM": "↑", "PSNR": "↑", "MUSIQ": "↑",
              "CLIP-Text": "↑", "CLIP-Image": "↑", "Region CLIP-T": "↑", "Region CLIP-I": "↑"}
    print("\n=== Final metrics ===")
    for k in ["FID","SSIM","PSNR","MUSIQ","CLIP-Text","CLIP-Image","Region CLIP-T","Region CLIP-I"]:
        if k in results:
            print(f"  {k}{arrows.get(k,'')}: {results[k]:.4f}")
    if "per_type" in results:
        print("\nPer-type:")
        for t in ["square","add","replace","extract"]:
            if t in results["per_type"]:
                vals = results["per_type"][t]
                parts = [f"{k}={v:.4f}" for k, v in vals.items()]
                print(f"  {t:8s}: {', '.join(parts)}")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nSaved → {args.out}")


if __name__ == "__main__":
    main()
